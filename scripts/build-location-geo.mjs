// Generates data/locations/geo.generated.ts from Natural Earth (public domain,
// via the world-atlas package). Run: node scripts/build-location-geo.mjs
// Add a market by adding an entry to MARKETS below and re-running.
import { readFileSync, writeFileSync } from "node:fs";
import { merge } from "topojson-client";

const load = (f) => JSON.parse(readFileSync(new URL(`../node_modules/world-atlas/${f}`, import.meta.url)));
// Coarse outlines keep the page light; small markets need the finer set to be recognisable.
const coarse = load("countries-110m.json");
const fine = load("countries-50m.json");
// City-states are a handful of points at 1:50m, so their close-up uses 1:10m.
const finest = load("countries-10m.json");

const EUROPE = ["008", "040", "056", "070", "100", "191", "196", "203", "208", "233", "246", "250", "276", "300", "348", "352", "372", "380", "428", "440", "442", "470", "498", "499", "528", "807", "578", "616", "620", "642", "688", "703", "705", "724", "752", "756"];

/** key → ISO 3166-1 numeric ids, and an optional box that drops far-flung territories from the close-up. */
const MARKETS = {
  india: { ids: ["356"], fineLens: true },
  usa: { ids: ["840"], lensBox: [-126, 24, -66, 50] },
  uk: { ids: ["826"], lensBox: [-9, 49.5, 2.5, 61], fineLens: true },
  uae: { ids: ["784"], fine: true, finestLens: true },
  canada: { ids: ["124"] },
  australia: { ids: ["036"], lensBox: [112, -44.5, 155, -9] },
  singapore: { ids: ["702"], fine: true, finestLens: true },
  europe: { ids: EUROPE, box: [-25, 34, 45, 72] },
};

// World projection: must match data/world-map.ts (equirectangular, 1000 × 371).
const K = 1000 / 350;
const world = ([lon, lat]) => [(lon + 170) * K, (74 - lat) * K];

function polygons(topo, ids) {
  const g = merge(topo, topo.objects.countries.geometries.filter((x) => ids.includes(String(x.id).padStart(3, "0"))));
  return g.coordinates; // MultiPolygon: [ [ring, ...holes], ... ]
}

const bbox = (ring) => ring.reduce((b, [x, y]) => [Math.min(b[0], x), Math.min(b[1], y), Math.max(b[2], x), Math.max(b[3], y)], [Infinity, Infinity, -Infinity, -Infinity]);
const inside = (ring, box) => {
  const b = bbox(ring);
  const cx = (b[0] + b[2]) / 2, cy = (b[1] + b[3]) / 2;
  return cx >= box[0] && cx <= box[2] && cy >= box[1] && cy <= box[3];
};

function path(polys, project, digits, minSize) {
  let d = "";
  for (const poly of polys) {
    const outer = poly[0].map(project);
    const b = bbox(outer);
    if (Math.max(b[2] - b[0], b[3] - b[1]) < minSize) continue;
    const f = (n) => Number(n.toFixed(digits));
    let last = "";
    const pts = [];
    for (const p of outer) {
      const s = `${f(p[0])},${f(p[1])}`;
      if (s !== last) pts.push(s);
      last = s;
    }
    if (pts.length > 3) d += `M${pts.join("L")}Z`;
  }
  return d;
}

const out = {};
for (const [key, m] of Object.entries(MARKETS)) {
  const pick = (topo) => {
    const p = polygons(topo, m.ids);
    return m.box ? p.filter((x) => inside(x[0], m.box)) : p;
  };
  const polys = pick(m.fine ? fine : coarse);
  const lensSource = m.finestLens ? pick(finest) : m.fine || m.fineLens ? pick(fine) : polys;
  const lensPolys = m.lensBox ? lensSource.filter((p) => inside(p[0], m.lensBox)) : lensSource;

  // Close-up: fit the shape into a 400-wide box, correcting for latitude.
  const all = lensPolys.flatMap((p) => p[0]);
  const [lonMin, latMin, lonMax, latMax] = bbox(all);
  const cos = Math.cos((((latMin + latMax) / 2) * Math.PI) / 180);
  const s = 400 / Math.max((lonMax - lonMin) * cos, latMax - latMin);
  const lens = { lonMin: +lonMin.toFixed(4), latMax: +latMax.toFixed(4), kx: +(s * cos).toFixed(4), ky: +s.toFixed(4), w: Math.ceil((lonMax - lonMin) * cos * s), h: Math.ceil((latMax - latMin) * s) };
  const project = ([lon, lat]) => [(lon - lonMin) * lens.kx, (latMax - lat) * lens.ky];

  // Label anchor on the world map: centre of the largest polygon.
  const biggest = [...polys].sort((a, b) => { const x = bbox(a[0]), y = bbox(b[0]); return (y[2] - y[0]) * (y[3] - y[1]) - (x[2] - x[0]) * (x[3] - x[1]); })[0][0];
  const bb = bbox(biggest);
  const centre = world([(bb[0] + bb[2]) / 2, (bb[1] + bb[3]) / 2]).map((n) => +n.toFixed(1));
  const wb = bbox(polys.flatMap((p) => p[0]).map(world));

  out[key] = {
    world: path(polys, world, 1, m.fine ? 0 : 1.5),
    centre,
    /** Too small to see at world scale: the map draws a ring around it instead. */
    tiny: Math.max(wb[2] - wb[0], wb[3] - wb[1]) < 20,
    lens: { ...lens, d: path(lensPolys, project, 0, m.finestLens ? 3 : m.fine ? 0 : 5) },
  };
}

const banner = `/**
 * GENERATED by scripts/build-location-geo.mjs. Do not edit by hand.
 * Country outlines from Natural Earth (public domain): 1:110m and 1:50m,
 * with 1:10m for the close-up of the smallest markets.
 * \`world\` is in the same projection as data/world-map.ts (1000 × 371).
 * \`lens\` is a close-up of the market on its own; project a city with
 * x = (lon - lonMin) * kx, y = (latMax - lat) * ky.
 */
export type MarketShape = { world: string; centre: [number, number]; tiny: boolean; lens: { lonMin: number; latMax: number; kx: number; ky: number; w: number; h: number; d: string } };

/** Projects a longitude and latitude onto the world map. */
export const WORLD_K = ${K};
export function projectWorld(lon: number, lat: number): [number, number] {
  return [(lon + 170) * WORLD_K, (74 - lat) * WORLD_K];
}

export const marketShapes: Record<string, MarketShape> = ${JSON.stringify(out)};
`;
writeFileSync(new URL("../data/locations/geo.generated.ts", import.meta.url), banner);
for (const [k, v] of Object.entries(out)) console.log(k, "world", v.world.length, "lens", v.lens.d.length, v.lens.w + "x" + v.lens.h, "tiny", v.tiny, v.centre);
